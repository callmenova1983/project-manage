-- PostgreSQL baseline corresponding to SQLite migrations 001 through 022.
-- JSON payloads remain TEXT to preserve the existing serialization contract.
-- Explicit rowid values preserve insertion order and notification cursors during import.

CREATE TABLE migrations (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,version BIGINT PRIMARY KEY, applied_at TEXT NOT NULL);

CREATE TABLE workspaces (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT PRIMARY KEY, name TEXT NOT NULL, revision BIGINT NOT NULL DEFAULT 1, time_zone TEXT NOT NULL DEFAULT 'UTC', settings_version BIGINT NOT NULL DEFAULT 1);

CREATE TABLE users (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), email TEXT UNIQUE NOT NULL, name TEXT NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'member' CHECK(role IN ('member','admin')), status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','disabled','pending')), requires_activation BIGINT NOT NULL DEFAULT 0, version BIGINT NOT NULL DEFAULT 1, username TEXT);

CREATE TABLE sessions (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), csrf TEXT NOT NULL, expires_at BIGINT NOT NULL);

CREATE TABLE projects (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT NOT NULL, workspace_id TEXT NOT NULL REFERENCES workspaces(id), version BIGINT NOT NULL, data TEXT NOT NULL, PRIMARY KEY(workspace_id,id));

CREATE TABLE tasks (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT NOT NULL, workspace_id TEXT NOT NULL, project_id TEXT NOT NULL, version BIGINT NOT NULL, data TEXT NOT NULL, PRIMARY KEY(workspace_id,id), FOREIGN KEY(workspace_id,project_id) REFERENCES projects(workspace_id,id));

CREATE TABLE activities (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), created_at TEXT NOT NULL, data TEXT NOT NULL);

CREATE TABLE proposals (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT NOT NULL, workspace_id TEXT NOT NULL REFERENCES workspaces(id), data TEXT NOT NULL, PRIMARY KEY(workspace_id,id));

CREATE TABLE idempotency (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,key TEXT NOT NULL,user_id TEXT NOT NULL REFERENCES users(id),request_hash TEXT NOT NULL,response TEXT NOT NULL,created_at BIGINT NOT NULL,PRIMARY KEY(user_id,key));

CREATE TABLE ai_requests (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  user_id TEXT NOT NULL REFERENCES users(id),
  key TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  status TEXT NOT NULL CHECK(status IN ('started','succeeded','failed')),
  response TEXT,
  created_at BIGINT NOT NULL,
  PRIMARY KEY(user_id,key)
);

CREATE TABLE ai_attempts (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id TEXT PRIMARY KEY,
  budget_id TEXT NOT NULL,
  user_id TEXT NOT NULL REFERENCES users(id),
  created_at BIGINT NOT NULL
);

CREATE TABLE intake_batches (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT NOT NULL, workspace_id TEXT NOT NULL REFERENCES workspaces(id), created_at TEXT NOT NULL, data TEXT NOT NULL, PRIMARY KEY(workspace_id,id));

CREATE TABLE user_activations(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),expires_at BIGINT NOT NULL,used_at BIGINT);

CREATE TABLE workspace_catalogs(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),data TEXT NOT NULL);

CREATE TABLE model_settings(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),data TEXT NOT NULL);

CREATE TABLE admin_audit(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT PRIMARY KEY,workspace_id TEXT NOT NULL REFERENCES workspaces(id),created_at TEXT NOT NULL,data TEXT NOT NULL);

CREATE TABLE model_logs(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT PRIMARY KEY,workspace_id TEXT NOT NULL REFERENCES workspaces(id),created_at TEXT NOT NULL,data TEXT NOT NULL);

CREATE TABLE workspace_directory (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),
  data TEXT NOT NULL
);

CREATE TABLE project_members (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT NOT NULL,
  project_id TEXT NOT NULL,
  user_id TEXT NOT NULL REFERENCES users(id),
  joined_at TEXT NOT NULL,
  last_edited_at TEXT NOT NULL,
  PRIMARY KEY(workspace_id,project_id,user_id),
  FOREIGN KEY(workspace_id,project_id) REFERENCES projects(workspace_id,id) ON DELETE CASCADE
);

CREATE TABLE workspace_project_order (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),
  data TEXT NOT NULL
);

CREATE TABLE workspace_ai_credentials (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),
  encrypted_config TEXT NOT NULL
);

CREATE TABLE "progress_materials" (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id TEXT NOT NULL,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  project_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  metadata TEXT NOT NULL,
  bytes BYTEA NOT NULL,
  images TEXT NOT NULL,
  PRIMARY KEY(workspace_id,id)
);

CREATE TABLE daily_logs (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  fingerprint TEXT NOT NULL,
  created_at TEXT NOT NULL,
  data TEXT NOT NULL,
  UNIQUE(workspace_id, fingerprint)
);

CREATE TABLE workspace_wecom_credentials (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),
  version BIGINT NOT NULL,
  encrypted_config TEXT NOT NULL
);

CREATE TABLE notification_accounts (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  preferences TEXT NOT NULL,
  following TEXT NOT NULL DEFAULT '[]',
  PRIMARY KEY(workspace_id,user_id)
);

CREATE TABLE notification_cursors (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),
  activity_row BIGINT NOT NULL,
  initialized_at TEXT NOT NULL
);

CREATE TABLE notifications (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  logical_key TEXT NOT NULL,
  generation BIGINT NOT NULL DEFAULT 1,
  signature TEXT NOT NULL,
  data TEXT NOT NULL,
  UNIQUE(workspace_id,user_id,logical_key)
);

CREATE TABLE notification_outbox (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id TEXT PRIMARY KEY,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  notification_id TEXT NOT NULL REFERENCES notifications(id),
  generation BIGINT NOT NULL,
  state TEXT NOT NULL,
  attempts BIGINT NOT NULL DEFAULT 0,
  next_at TEXT NOT NULL,
  error TEXT NOT NULL DEFAULT '',
  external_id TEXT,
  config_version BIGINT,
  binding_version BIGINT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(notification_id,generation)
);

CREATE TABLE notification_wecom_config (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),
  version BIGINT NOT NULL,
  encrypted_config TEXT NOT NULL
);

CREATE TABLE notification_bindings (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  employee_id TEXT NOT NULL,
  corp_id TEXT NOT NULL,
  wecom_user_id TEXT NOT NULL,
  fingerprint TEXT NOT NULL,
  version BIGINT NOT NULL,
  confirmed_at TEXT NOT NULL,
  PRIMARY KEY(workspace_id,user_id)
);

CREATE TABLE notification_directory_scope (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),
  corp_id TEXT NOT NULL,
  directory_version BIGINT NOT NULL,
  synced_at TEXT NOT NULL
);

CREATE TABLE project_redirects (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  source_id TEXT NOT NULL,
  target_id TEXT NOT NULL,
  created_at TEXT NOT NULL,
  PRIMARY KEY(workspace_id,source_id)
);

CREATE TABLE assistant_sessions (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id),
  user_id TEXT NOT NULL REFERENCES users(id),
  version BIGINT NOT NULL,
  updated_at TEXT NOT NULL,
  data TEXT NOT NULL,
  PRIMARY KEY(workspace_id,user_id)
);

CREATE TABLE personal_access_tokens (
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT UNIQUE NOT NULL,
  prefix TEXT NOT NULL,
  created_at TEXT NOT NULL,
  last_used_at TEXT
);

CREATE TABLE wecom_login_config(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id),version BIGINT NOT NULL,encrypted_config TEXT NOT NULL);

CREATE TABLE wecom_login_states(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,state_hash TEXT PRIMARY KEY,browser_hash TEXT NOT NULL,workspace_id TEXT NOT NULL REFERENCES workspaces(id),config_version BIGINT NOT NULL,return_to TEXT NOT NULL,expires_at BIGINT NOT NULL);

CREATE TABLE wecom_login_events(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,id TEXT PRIMARY KEY,workspace_id TEXT NOT NULL REFERENCES workspaces(id),created_at TEXT NOT NULL,outcome TEXT NOT NULL);

CREATE TABLE wecom_login_sessions(
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,token_hash TEXT PRIMARY KEY REFERENCES sessions(token_hash) ON DELETE CASCADE,workspace_id TEXT NOT NULL,corp_id TEXT NOT NULL,wecom_user_id TEXT NOT NULL);

CREATE INDEX activity_workspace_date ON activities(workspace_id,created_at DESC);

CREATE INDEX task_project ON tasks(workspace_id,project_id);

CREATE INDEX ai_attempt_budget ON ai_attempts(budget_id);

CREATE INDEX intake_workspace_date ON intake_batches(workspace_id,created_at DESC);

CREATE INDEX model_logs_workspace_date ON model_logs(workspace_id,created_at DESC);

CREATE INDEX admin_audit_workspace_date ON admin_audit(workspace_id,created_at DESC);

CREATE UNIQUE INDEX users_username_unique ON users(lower(username)) WHERE username IS NOT NULL;

CREATE INDEX progress_materials_project ON progress_materials(workspace_id,project_id);

CREATE INDEX notification_recipient ON notifications(workspace_id,user_id);

CREATE INDEX notification_due ON notification_outbox(state,next_at);

CREATE INDEX activity_workspace_row ON activities(workspace_id, rowid);
